export const ICON_BY_SLUG: Record<string, IconEntry> = ICON_REGISTRY.reduce(
  (acc, entry) => {
    acc[entry.slug] = entry;
    return acc;
  },
  {} as Record<string, IconEntry>
);

export const createCustomIconComponent = (
  svgMarkup: string,
  _viewBox = '0 0 24 24'
): React.FC<LucideProps> => {
  return function CustomSvgIcon({ className = '', style, color = 'currentColor', ...rest }: LucideProps) {
    return React.createElement('span', {
      className: `inline-flex items-center justify-center shrink-0 [&>svg]:w-full [&>svg]:h-full [&>svg]:max-w-full [&>svg]:max-h-full ${className}`,
      style: { color, ...style },
      dangerouslySetInnerHTML: { __html: svgMarkup },
      'aria-hidden': 'true',
      ...rest,
    });
  };
};

const warnedUnknownIcons = new Set<string>();

export const resolveIcon = (
  iconRef: string | null | undefined,
  customIconsCache?: Record<string, CustomIcon> | CustomIcon[] | Map<string, CustomIcon>
): React.FC<LucideProps> | null => {
  if (!iconRef) {
    return ICON_BY_SLUG['award']?.component || null;
  }

  const trimmed = iconRef.trim();

  // 1. Custom icon format: "custom:abc123"
  if (trimmed.startsWith('custom:')) {
    const customId = trimmed.slice(7);

    let customDoc: CustomIcon | undefined;
    if (customIconsCache) {
      if (customIconsCache instanceof Map) {
        customDoc = customIconsCache.get(customId);
      } else if (Array.isArray(customIconsCache)) {
        customDoc = customIconsCache.find((c) => c.id === customId);
      } else if (typeof customIconsCache === 'object') {
        customDoc = customIconsCache[customId];
      }
    }

    if (customDoc && customDoc.svg) {
      return createCustomIconComponent(customDoc.svg, customDoc.viewBox);
    }
  }

  // 2. Lucide format: strip "lucide:" prefix if present
  const slug = trimmed.startsWith('lucide:') ? trimmed.slice(7) : trimmed;
  if (ICON_BY_SLUG[slug]) {
    return ICON_BY_SLUG[slug].component;
  }

  // 3. Fallback to "award" and warn once per session
  if (!warnedUnknownIcons.has(trimmed)) {
    warnedUnknownIcons.add(trimmed);
    console.warn(
      `[resolveIcon] Ícone desconhecido: "${trimmed}". Usando ícone padrão (award).`
    );
  }

  return ICON_BY_SLUG['award']?.component || null;
};

